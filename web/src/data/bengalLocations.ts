export const DEFAULT_CITY = BENGAL_CITIES[0];

export function findNearestBengalCity(lat: number, lon: number): BengalCity {
  let nearest = BENGAL_CITIES[0];
  let minDistance = Infinity;

  for (const city of BENGAL_CITIES) {
    const dLat = ((city.latitude - lat) * Math.PI) / 180;
    const dLon = ((city.longitude - lon) * Math.PI) / 180;
    const a =
      Math.sin(dLat / 2) * Math.sin(dLat / 2) +
      Math.cos((lat * Math.PI) / 180) *
        Math.cos((city.latitude * Math.PI) / 180) *
        Math.sin(dLon / 2) *
        Math.sin(dLon / 2);
    const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
    const d = 6371 * c;
    if (d < minDistance) {
      minDistance = d;
      nearest = city;
    }
  }

  return nearest;
}
